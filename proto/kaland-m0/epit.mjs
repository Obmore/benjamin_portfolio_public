// Generates adat.js: every value the M0 prototype draws, from a named source in this repository.
// Run from anywhere: node proto/kaland-m0/epit.mjs   (Node 22 strips the TypeScript types of the imported .ts files)
//
// The temperature series is the demo's own simulation: the sliced source of public/demos/adatgyujto/app.js (from `const SHIFTS` to the
// "megjelenítés" marker) run in Node, 60 warm-up steps as the demo does at load, then one step per demo minute until the shift change at 14:00.
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { CNC1_HOMERSEKLET, QR_MODULOK } from '../../src/content/sorozatok.ts'
import { IDOVONAL, TERULETEK } from '../../src/content/tapasztalat.ts'
import { teny, ELO_FELIRAT } from '../../src/content/munkak.ts'
import { VALLALKOZO, levelCim } from '../../src/content/alapadatok.ts'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8')

// --- GÉPADAT: the demo's own minutes -------------------------------------------------------------------------------------------------
const demoSrc = read('public/demos/adatgyujto/app.js')
const a = demoSrc.indexOf('const SHIFTS')
const b = demoSrc.indexOf('// ----- megjelenítés -----')
assert.ok(a > 0 && b > a, 'the demo source markers moved')
const demo = new Function('location', `${demoSrc.slice(a, b)}\nreturn { state, step, announce }`)({ search: '' })
const WARMUP = 60 // the demo simulates 60 minutes at load (6:00-6:59), so that the history exists; the run then starts at 7:00
const sorozat = []
for (let i = 0; i < 480; i++) {
  demo.step()
  sorozat.push(demo.state[0].temp) // CNC-1 at demo minute 6:00 + i (the sample the demo pushes to its history in this step)
}
// The first 60 samples (the demo's warm-up hour) are the ones the site already pins as CNC1_HOMERSEKLET (rounded to one decimal there).
assert.deepEqual(sorozat.slice(0, 60).map((v) => Math.round(v * 10) / 10), [...CNC1_HOMERSEKLET])
const valt = demo.announce.find((x) => x.text.startsWith('Műszakváltás'))
assert.ok(valt, 'the demo announces a shift change at 14:00')

// --- the rest: strings and facts that exist in the repository ------------------------------------------------------------------------
const adat = {
  forras: 'proto/kaland-m0/epit.mjs: public/demos/adatgyujto/app.js (run), src/content/sorozatok.ts, tapasztalat.ts, munkak.ts, alapadatok.ts',
  gepadat: {
    forras: 'public/demos/adatgyujto/app.js, CNC-1, seed 20261026, step()',
    egyseg: '°C',
    lepes: '1 perc',
    kezdetPerc: 6 * 60,
    elozmeny: WARMUP, // samples 0..59 exist at load (6:00-6:59); the run starts at index 59 = 7:00
    ertekek: sorozat,
    muszakValtas: valt.text,
  },
  qr: { forras: 'src/content/sorozatok.ts QR_MODULOK (the demo library, 29 x 29)', modulok: [...QR_MODULOK], url: 'https://ottbenjamin.hu/demos/kezikonyv/' },
  honlap: { forras: 'public/work/lelek-es-nyelv-telefon.webp (block means computed in the browser, linear light)', kep: '/work/lelek-es-nyelv-telefon.webp' },
  evek: {
    forras: 'src/content/tapasztalat.ts IDOVONAL (area and years only, no employer: owner decision 2026-11-05)',
    idovonal: IDOVONAL.map((i) => ({ kezdet: i.kezdet, veg: i.veg ?? null, terulet: i.terulet })),
    teruletek: TERULETEK.map((t) => ({ id: t.id, cim: t.cim.replaceAll('­', ''), reszlet: t.reszlet })),
    nev: VALLALKOZO.nev,
    szakma: VALLALKOZO.szakma,
  },
  munkak: {
    honlap: { nev: teny('lelek-es-nyelv').nev, href: teny('lelek-es-nyelv').href, felirat: ELO_FELIRAT, kulso: true },
    gepkonyv: { nev: teny('kezikonyv').nev, href: teny('kezikonyv').href, felirat: 'Próbálja ki', kulso: false },
    gepadat: { nev: teny('adatgyujto').nev, href: teny('adatgyujto').href, felirat: 'Próbálja ki', kulso: false },
  },
  kapcsolat: { email: VALLALKOZO.email, felirat: 'Levelet írok', href: levelCim({ targy: 'Kérdés az oldalról' }) },
}

const ki = path.join(root, 'proto/kaland-m0/adat.js')
fs.writeFileSync(ki, `// GENERATED by epit.mjs: do not edit. Every number is a run or a copy of a named source.\nexport default ${JSON.stringify(adat)}\n`)
console.log('adat.js written:', fs.statSync(ki).size, 'bytes;', sorozat.length, 'CNC-1 samples;', 'shift sentence:', valt.text)
